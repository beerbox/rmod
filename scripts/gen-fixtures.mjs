// Generates tests/fixtures/index.ts from tests/fixtures/*.json, because the
// test kit imports only code files. The JSON files stay the source of truth.
// Usage: node scripts/gen-fixtures.mjs [--check]
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const dir = join(import.meta.dirname, '..', 'tests', 'fixtures')
const out = join(dir, 'index.ts')
const files = readdirSync(dir).filter(f => f.endsWith('.json')).sort()

const name = f => f.replace(/\.json$/, '').toUpperCase().replace(/[^A-Z0-9]+/g, '_')
let ts = '// GENERATED by scripts/gen-fixtures.mjs from tests/fixtures/*.json. Do not edit.\n'
ts += '// Each value is the response body text, exactly as a server would send it.\n\n'
const seen = new Map()
for (const f of files) {
  const id = name(f)
  if (!/^[A-Z_][A-Z0-9_]*$/.test(id)) throw new Error(`${f}: export name ${id} is not a valid identifier`)
  if (seen.has(id)) throw new Error(`${f} and ${seen.get(id)} both map to ${id}: rename one`)
  seen.set(id, f)
  const text = readFileSync(join(dir, f), 'utf8')
  JSON.parse(text) // fail loudly on a malformed fixture
  ts += `export const ${id} = ${JSON.stringify(text)}\n`
}

if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8') : ''
  if (current !== ts) {
    console.error('tests/fixtures/index.ts is stale: run npm run fixtures')
    process.exit(1)
  }
  console.log('fixtures up to date')
} else {
  writeFileSync(out, ts)
  console.log(`wrote ${files.length} fixtures to tests/fixtures/index.ts`)
}
